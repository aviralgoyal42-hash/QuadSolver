// Multi-core driver. Runs independent solver instances on worker threads.
//
// One solve is split into arms: the same state framed by a different
// whole-cube rotation (or with a prefix move), each searched on its own core
// with the full time budget, keeping the shortest verified answer. The
// single-threaded solver could not afford this, because its arms had to share
// one budget and the split cost about what the extra framings gained (see
// STATUS.md, "Multi-start over prepended moves"). With one core per arm they
// no longer share anything.
"use strict";

const os = require("os");
const path = require("path");
const { Worker } = require("worker_threads");
const { sharedEdge3 } = require("./engine");

// The 24 whole-cube orientations, as products of x, y and z written in wide
// turns. Generated by breadth-first search from the solved cube.
const ROTATIONS = [
  "", "Uw Dw'", "Rw Lw'", "Fw Bw'", "Uw Dw' Uw Dw'", "Uw Dw' Rw Lw'", "Uw Dw' Fw Bw'",
  "Rw Lw' Rw Lw'", "Rw Lw' Fw Bw'", "Fw Bw' Uw Dw'", "Fw Bw' Fw Bw'", "Uw Dw' Uw Dw' Uw Dw'",
  "Uw Dw' Uw Dw' Rw Lw'", "Uw Dw' Uw Dw' Fw Bw'", "Uw Dw' Rw Lw' Rw Lw'", "Uw Dw' Fw Bw' Uw Dw'",
  "Uw Dw' Fw Bw' Fw Bw'", "Rw Lw' Rw Lw' Rw Lw'", "Rw Lw' Rw Lw' Fw Bw'", "Fw Bw' Fw Bw' Fw Bw'",
  "Uw Dw' Uw Dw' Uw Dw' Fw Bw'", "Uw Dw' Uw Dw' Fw Bw' Uw Dw'", "Uw Dw' Rw Lw' Rw Lw' Fw Bw'",
  "Uw Dw' Fw Bw' Fw Bw' Fw Bw'"
];

const PREFIXES = [];
for (const f of ["U", "R", "F", "D", "L", "B", "Uw", "Rw", "Fw", "Dw", "Lw", "Bw"]) {
  for (const s of ["", "2", "'"]) PREFIXES.push(f + s);
}

// Rotations first, since they cost no moves; then single prefix moves.
function armList(n) {
  const arms = [];
  for (let i = 0; i < n && i < ROTATIONS.length; i++) arms.push({ rot: ROTATIONS[i], prefix: "" });
  for (let i = 0; arms.length < n; i++) {
    arms.push({ rot: ROTATIONS[i % ROTATIONS.length], prefix: PREFIXES[(i * 7) % PREFIXES.length] });
  }
  return arms;
}

// Two ways to keep time, chosen per solve with `timing`.
//
// "average" (the default) aims the mean solve time at the budget: threads
// search until AVERAGE_OVERHEAD_MS before it, which is what relabelling,
// verification and the message back cost on average, and the pool cuts off any
// straggler once the solve is overTime(budget) past it.
//
// "hard" treats the budget as a cap no solve may exceed. Threads stop
// ARM_MARGIN_MS early and the pool answers POOL_MARGIN_MS early. With 50 and
// 20 ms, 1 solve in 300 at a 1.5 s budget finished 21 ms late
// (results/confirm-2026-11-10.txt): both the threads and the pool's own timer
// were late at once, which is the whole process being held off the CPU.
// Nothing in user space can rule that out on a desktop OS, so the margins are
// sized to absorb a stall of about two scheduler quanta. They cost search
// time, a quarter of the budget at 300 ms, which is why this is not the
// default.
const AVERAGE_OVERHEAD_MS = 13;
const ARM_MARGIN_MS = 70;
const POOL_MARGIN_MS = 40;

function overTime(budgetMs) {
  return Math.max(30, Math.min(150, Math.round(budgetMs * 0.12)));
}

// Reduction prefixes each thread builds for a sharded solve. A bigger pool
// holds shorter reductions, but building it costs time the search needs.
// Measured on 12 threads (RESULTS.md): the average is flat across a wide range
// around this line, 75 to 150 per thread at 300 ms and 300 to 1000 at 1.5 s,
// and gets worse well outside it. The cap is the largest size tested.
function quotaFor(budgetMs) {
  return Math.max(60, Math.min(2400, Math.round(budgetMs * 0.4)));
}

const WARM_UP_SCRAMBLES = [
  "U2 D' F' U2 L2 F' B R2 D2 F R2 L B L2 F B2 R2 U2 D' L Rw2 Fw2 L' B' Fw2 L' D2 Rw2 Uw2 F L B2 U' Uw2 L Uw' R U2 Rw U2 F' Fw' Rw Fw Rw' D'",
  "B' U2 F U2 B R2 D2 L2 B2 L' U D' F B D F' D2 L D' Fw2 L Fw2 D' Uw2 F2 D R D2 R' Rw2 Fw U2 Rw2 B' L' Uw R B Rw2 Uw' Rw' Fw Rw",
  "L' F' L2 U2 R2 U B2 U F2 D' B2 U2 F D2 B U2 R' L' U' L Fw2 L B2 Uw2 L' B2 U' D Fw2 L Rw2 D F2 Fw' Rw2 B Rw2 D2 R' Uw' L Fw Uw' L F",
  "D2 B2 L D2 R' U B L D2 R2 B2 R U2 R2 U2 R U2 D B' U2 Fw2 D2 L' D' Uw2 F2 L' D' F2 L' Fw2 L' Fw' Uw2 B2 Rw2 Fw' U Fw2 R Uw' F2 B2 Rw' Fw L"
];

class SolverPool {
  // deepEdge (default on) gives every thread the full-depth phase-3 edge
  // table: built once, about 20 s, then cached on disk and shared in memory.
  // Turn it off to run the search exactly as upstream does, which is what the
  // "stock" baseline must use.
  constructor({ threads = os.availableParallelism ? os.availableParallelism() : os.cpus().length, phase2Sols = 300, deepEdge = true, log } = {}) {
    this.threads = Math.max(1, threads | 0);
    this.deepEdge = !!deepEdge;
    const e3 = this.deepEdge ? sharedEdge3({ log }) : null;
    this.edge3 = e3 ? { source: e3.source, ms: e3.ms } : null;
    const edge3 = e3 ? { maxPrun: e3.maxPrun, buffer: e3.buffer } : null;
    this.queue = [];
    this.pending = new Map();
    this.nextId = 1;
    this.idle = [];
    this.workers = [];
    this.initMs = [];
    const t0 = Date.now();
    this.ready = Promise.all(Array.from({ length: this.threads }, () => new Promise((resolve, reject) => {
      const w = new Worker(path.join(__dirname, "pool-worker.js"), { workerData: { phase2Sols, edge3 } });
      w.once("error", reject);
      w.on("message", (m) => {
        if (m.type === "ready") {
          this.initMs.push(m.ms);
          this.idle.push(w);
          this._pump();
          resolve();
        } else if (m.type === "done") {
          const cb = this.pending.get(m.id);
          this.pending.delete(m.id);
          this.idle.push(w);
          this._pump();
          cb(m.result);
        }
      });
      this.workers.push(w);
    }))).then(() => Date.now() - t0);
  }

  _pump() {
    while (this.idle.length && this.queue.length) {
      const { msg, resolve } = this.queue.shift();
      const w = this.idle.pop();
      this.pending.set(msg.id, resolve);
      w.postMessage(msg);
    }
  }

  // Runs one message on the next free worker.
  run(msg) {
    return new Promise((resolve) => {
      this.queue.push({ msg: Object.assign({ id: this.nextId++ }, msg), resolve });
      this._pump();
    });
  }

  // Solves one state across `arms` framings (default: one per thread) and
  // returns the shortest verified solution. budgetMs is wall clock for the
  // whole solve: when there are more arms than threads, they run in rounds
  // and each gets a proportional slice.
  //
  // mode "shard" (default) splits one search: every thread takes a slice of
  // the reduction candidates and they share the incumbent, so N threads
  // screen roughly N times as many reductions. mode "rotate" gives each
  // thread a whole search of a rotated copy; the copies tend to converge on
  // the same answer, so it buys much less.
  //
  // groups > 1 (shard mode only) splits the threads into that many groups,
  // each sharding one search of a differently rotated cube with its own
  // shared incumbent, so the answer gets the best of several framings.
  //
  // poolTotal is the number of reduction prefixes a sharded search builds
  // across all its threads; each thread builds its own share and nothing
  // else. Left unset, each thread's share follows quotaFor(budgetMs).
  //
  // timing is "average" or "hard"; see the constants at the top of this file.
  async solve(state, { budgetMs = 30000, arms = this.threads, mode = "shard", groups = 1, poolTotal, timing = "average", options = {}, onArm } = {}) {
    if (timing !== "average" && timing !== "hard") throw new Error('timing must be "average" or "hard"');
    await this.ready;
    // A previous solve may have answered at its deadline with arms still
    // finishing; let them clear so this one starts with every thread free.
    if (this.settling) await this.settling;
    const t0 = Date.now();
    const n = Math.max(1, arms);
    const sharded = mode === "shard" && n > 1;
    let list;
    if (sharded) {
      const g = Math.max(1, Math.min(groups, n, ROTATIONS.length));
      // One incumbent for every group. A total is a move count for the
      // original cube whichever rotation produced it, so it is a valid bound
      // everywhere. It also lets a group that has found nothing yet stop at
      // the deadline once any other group holds an answer; with one buffer
      // per group, such a group kept searching and overran the budget.
      const shared = new SharedArrayBuffer(4);
      new Int32Array(shared)[0] = 0x7fffffff;
      list = [];
      for (let j = 0; j < g; j++) {
        // Spread any remainder over the first groups.
        const size = Math.floor(n / g) + (j < n % g ? 1 : 0);
        for (let k = 0; k < size; k++) {
          list.push({
            rot: ROTATIONS[j], prefix: "", shard: k, shards: size, shared,
            options: Object.assign({
              prefixShard: true,
              fastPhase2: true,
              skipPadded: true,
              // The deep pass works through one thread's own shortlist, and
              // with the search split it found nothing to do: at 10 s it
              // ended solves 1.5 s early for the same average.
              deepMs: 0,
              poolSize: poolTotal ? Math.max(4, Math.ceil(poolTotal / size)) : quotaFor(budgetMs)
            }, options)
          });
        }
      }
    } else {
      list = armList(n);
    }
    // Shards must run concurrently to share pruning, so never queue them.
    if (sharded && n > this.threads) throw new Error("shard mode needs arms <= threads");
    const rounds = Math.ceil(list.length / this.threads);
    const hard = timing === "hard";
    const armBudget = Math.max(100, Math.floor(budgetMs / rounds) - (hard ? ARM_MARGIN_MS : AVERAGE_OVERHEAD_MS));
    let best = null;
    const results = new Array(list.length).fill(null);
    let firstAnswer;
    const gotAnswer = new Promise((resolve) => { firstAnswer = resolve; });
    const all = Promise.all(list.map(async (arm, i) => {
      const r = await this.run({
        type: "arm", state, rot: arm.rot, prefix: arm.prefix,
        shard: arm.shard, shards: arm.shards, shared: arm.shared,
        budgetMs: armBudget, options: arm.options || options
      });
      r.arm = i;
      results[i] = r;
      if (!r.error && (!best || r.moves < best.moves || (r.moves === best.moves && r.oriented && !best.oriented))) best = r;
      if (best) firstAnswer();
      if (onArm) onArm(r, arm);
      return r;
    }));
    // Each arm stops itself, but a 3x3x3 call cannot be interrupted and the
    // machine may be busy, so the pool also keeps the clock: at its own
    // deadline it answers with the best verified solution reported so far and
    // lets any straggler finish unheard. Only if no arm has answered yet does
    // it wait for the first. In multi-round modes every arm runs for a slice
    // of the budget, so there is nothing to cut short and all are awaited.
    let timer;
    if (rounds === 1) {
      // The timer itself can fire a scheduler quantum or two late (about
      // 31 ms on Windows) because every core is busy, hence POOL_MARGIN_MS.
      const cutoff = hard ? budgetMs - POOL_MARGIN_MS : budgetMs + overTime(budgetMs) - POOL_MARGIN_MS;
      const deadline = new Promise((resolve) => { timer = setTimeout(resolve, Math.max(0, cutoff - (Date.now() - t0))); });
      await Promise.race([all, deadline.then(() => gotAnswer)]);
      clearTimeout(timer);
    } else {
      await all;
    }
    if (!best) {
      await all;
      const failed = results.find((r) => r && r.error);
      return { error: (failed && failed.error) || "no arm produced a solution", ms: Date.now() - t0 };
    }
    const late = results.filter((r) => r === null).length;
    // Arms still running hold their workers; wait for them before the next
    // solve is timed, but not before answering this one.
    this.settling = late ? all.then(() => {}) : null;
    return Object.assign({}, best, {
      ms: Date.now() - t0,
      arms: list.length,
      late,
      armMoves: results.map((r) => (!r || r.error ? null : r.moves)),
      directMoves: !results[0] || results[0].error ? null : results[0].moves
    });
  }

  // Solves a few fixed scrambles and throws the answers away. A fresh thread
  // runs unoptimised code, and the first solve in a new process can take a
  // third longer than its budget: with a 300 ms budget it was measured at
  // 404 ms. This belongs to start-up, like building the tables.
  async warmUp({ solves = 4, budgetMs = 300 } = {}) {
    await this.ready;
    for (let i = 0; i < solves; i++) {
      const { state } = await this.scramble(WARM_UP_SCRAMBLES[i % WARM_UP_SCRAMBLES.length]);
      await this.solve(state, { budgetMs });
    }
  }

  baseline(state) { return this.run({ type: "baseline", state }); }
  scramble(scramble) { return this.run({ type: "scramble", scramble }); }
  random() { return this.run({ type: "random" }); }

  close() { return Promise.all(this.workers.map((w) => w.terminate())); }
}

module.exports = { SolverPool, ROTATIONS, PREFIXES, armList, quotaFor, overTime };
